// Builds js/levels.js from tools/chapters.json.
//
// Each level slot either fixes `rows`, or describes a search (see curate.mjs) and optionally which
// of the ranked candidates to take (`pick`, default 0). Results are cached in tools/.cache/ so
// that tweaking one slot does not reshuffle the others.
//
// usage: node tools/build-levels.mjs [--fresh] [--only chapter.level] [--chapter n]
//   --chapter n  only search chapter n (1-based) and update the cache; run without it to write
//                js/levels.js. Chapters can be searched in parallel this way.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { curate, evaluate, describe } from './curate.mjs';
import { rng, show } from './lib.mjs';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const config = JSON.parse(readFileSync(here('./chapters.json'), 'utf8'));
const chapterArg = process.argv.indexOf('--chapter');
const onlyChapter = chapterArg > 0 ? Number(process.argv[chapterArg + 1]) : 0;
const cachePath = (c) => here(`./.cache/chapter-${c}.json`);
const fresh = process.argv.includes('--fresh');
const onlyArg = process.argv.indexOf('--only');
const only = onlyArg > 0 ? process.argv[onlyArg + 1] : null;
mkdirSync(here('./.cache'), { recursive: true });
const loadCache = (c) => (!fresh && existsSync(cachePath(c)) ? JSON.parse(readFileSync(cachePath(c), 'utf8')) : {});

const chapters = [];
config.chapters.forEach((chapter, c) => {
  if (onlyChapter && onlyChapter !== c + 1) return;
  const cache = loadCache(c + 1);
  const levels = [];
  chapter.levels.forEach((slot, l) => {
    const tag = `${c + 1}.${l + 1}`;
    const slotKey = JSON.stringify({ ...slot, tip: undefined });
    let rows = slot.rows;
    let info;
    if (!rows) {
      const hit = cache[tag];
      if (hit && hit.slotKey === slotKey && (!only || only !== tag)) {
        rows = hit.rows;
      } else {
        const found = curate(slot, slot.seed || 1000 + c * 100 + l);
        const choice = found[Math.min(slot.pick || 0, found.length - 1)];
        if (!choice) throw new Error(`no candidate for ${tag} ${chapter.name}`);
        rows = choice.rows;
        cache[tag] = { slotKey, rows };
        writeFileSync(cachePath(c + 1), JSON.stringify(cache, null, 1));
        console.error(`searched ${tag}: ${found.length} matches`);
      }
    }
    info = evaluate(rows, rng(7), 600);
    if (!info) throw new Error(`level ${tag} does not verify`);
    console.log(`\n${tag} ${chapter.name}  ${describe(info)}`);
    console.log(show(rows));
    levels.push({ rows, tip: slot.tip, info });
  });
  chapters.push({ name: chapter.name, blurb: chapter.blurb, pieces: chapter.pieces, levels });
});

if (onlyChapter) process.exit(0);

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
let js = `/*
 * knights out — level set. Generated by tools/build-levels.mjs from tools/chapters.json;
 * every level is verified solvable. Comments note the shortest solution (par), how many
 * solutions exist (for levels with echoes: how many within two jumps of par), and how often
 * random-but-careful play wins.
 *
 *   x hole   . dark   o lit   K knight   S shadow knight   M mirror knight
 *   (lowercase s / m: an echo knight standing on a lit square)
 */
(function (root) {
  const CHAPTERS = [\n`;
for (const ch of chapters) {
  js += `    {\n      name: ${q(ch.name)},\n      blurb: ${q(ch.blurb)},\n      pieces: ${q(ch.pieces)},\n      levels: [\n`;
  for (const lv of ch.levels) {
    const i = lv.info;
    const within = /[SMsm]/.test(lv.rows.join('')) ? ' within par+2' : '';
    js += `        // par ${i.par} · ${i.sols === 1 ? 'unique' : i.sols + ' solutions'}${within} · careful random play wins ${(i.smart * 100).toFixed(1)}%\n`;
    js += `        { rows: [${lv.rows.map(q).join(', ')}]${lv.tip ? `, tip: ${q(lv.tip)}` : ''} },\n`;
  }
  js += `      ],\n    },\n`;
}
js += `  ];
  if (typeof module === 'object' && module.exports) module.exports = CHAPTERS;
  else root.KNIGHTS_CHAPTERS = CHAPTERS;
})(typeof self !== 'undefined' ? self : this);
`;
writeFileSync(here('../js/levels.js'), js);
console.error('\nwrote js/levels.js');
